import { test, expect } from './fixtures';
import { startPaper, syntheticDoc } from './helpers';

test('board mode leaves a blank half and reveals only on request', async ({ page }) => {
  const doc = syntheticDoc([{ id: 'p1', count: 3 }]);
  const data = doc as typeof doc & { papers: { questions: { explanation?: string }[] }[] };
  data.papers[0]!.questions[0]!.explanation = 'A synthetic explanation for classroom review.';
  await page.goto('./');
  await expect(page.getByRole('button', { name: /Continue without an account|Import a pack file/ }).first()).toBeVisible();
  const guest = page.getByRole('button', { name: 'Continue without an account', exact: true });
  if (await guest.isVisible()) await guest.click();
  await page.getByRole('button', { name: 'Import a pack file', exact: true }).click();
  await page.getByRole('dialog').locator('textarea').fill(JSON.stringify(data));
  await expect(page.getByText('Valid', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Review import/ }).click();
  await page.getByRole('button', { name: 'Import', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Synthetic Physics', level: 1 })).toBeVisible();
  await startPaper(page, 0, { practice: true });
  await page.getByRole('button', { name: 'Board mode', exact: true }).click();
  const blank = page.getByTestId('board-blank');
  await expect(blank).toBeVisible();
  expect(await blank.evaluate((el) => ({ children: el.childElementCount, text: el.textContent, pointer: getComputedStyle(el).pointerEvents, background: getComputedStyle(el).backgroundColor, touch: el.getAttribute('ontouchstart'), mouse: el.getAttribute('onpointerdown') }))).toEqual({ children: 0, text: '', pointer: 'none', background: 'rgb(255, 255, 255)', touch: null, mouse: null });
  await page.screenshot({ path: '/tmp/mcq-board-light.png' });
  const box = await blank.boundingBox();
  const viewport = page.viewportSize()!;
  expect(box!.width).toBeCloseTo(viewport.width / 2, 0);
  expect(box!.x).toBeCloseTo(viewport.width / 2, 0);
  await expect(page.getByText('Answer: B', { exact: true })).toHaveCount(0);
  await expect(page.getByText('A synthetic explanation for classroom review.')).toHaveCount(0);
  await page.getByRole('button', { name: 'Cross out option A', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Cross out option A, crossed out' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Reveal answer', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByText('Answer: B', { exact: true })).toBeVisible();
  await expect(page.getByText('A synthetic explanation for classroom review.')).toHaveCount(0);
  await page.getByRole('button', { name: 'Reveal explanation', exact: true }).click();
  await expect(page.getByText('A synthetic explanation for classroom review.')).toBeVisible();
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  expect(await blank.evaluate((el) => getComputedStyle(el).backgroundColor)).toBe('rgb(13, 14, 16)');
  await page.screenshot({ path: '/tmp/mcq-board-dark.png' });
  await page.getByLabel('Text size', { exact: true }).selectOption('36');
  await expect(page.locator('.board-stem')).toHaveCSS('font-size', '36px');
  const blankBeforeScroll = await blank.boundingBox();
  await page.locator('.board-question-pane').evaluate((el) => { el.scrollTop = 80; });
  expect(await blank.boundingBox()).toEqual(blankBeforeScroll);
  await page.getByRole('button', { name: 'Flag for revisit', exact: true }).click();
  await page.getByLabel('Question number', { exact: true }).fill('3');
  await page.getByLabel('Question number', { exact: true }).press('Enter');
  await expect(page.getByRole('heading', { name: 'Question 3', exact: true })).toBeVisible();
  await expect(page.getByText('Answer: B', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Revisit (1)', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Question 1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Fullscreen', exact: true }).click();
  await expect.poll(() => page.evaluate(() => document.fullscreenElement?.className)).toBe('board');
  await page.getByRole('button', { name: 'Exit fullscreen', exact: true }).click();
  await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(false);
  await page.getByRole('button', { name: 'Exit board mode', exact: true }).click();
  await expect(page.locator('.qcard')).toBeVisible();
  await expect(page.getByRole('radio', { name: /Option A/ })).toHaveClass(/option-eliminated/);
  await expect(page.getByRole('radio', { name: /Option A/ })).toHaveAttribute('aria-checked', 'false');
  await page.getByRole('button', { name: 'Board mode', exact: true }).click();
  await expect(page.locator('.board-stem')).toHaveCSS('font-size', '36px');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(blank).toHaveCount(0);
  await expect(page.locator('.qcard')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Board mode', exact: true })).toHaveCount(0);
  await page.screenshot({ path: '/tmp/mcq-session-mobile.png' });
});
